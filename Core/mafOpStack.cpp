#include "mafOp.h"
#include "mafOpStack.h"

//----------------------------------------------------------------------------
mafOpStack::mafOpStack() = default;
//----------------------------------------------------------------------------

//----------------------------------------------------------------------------
mafOpStack::~mafOpStack( ) 
/**  calls delete on every inserted op */
//----------------------------------------------------------------------------
{
  Clear();
}

//----------------------------------------------------------------------------
bool mafOpStack::IsEmpty() const
//----------------------------------------------------------------------------
{
  return (m_Stack == nullptr);
}

//----------------------------------------------------------------------------
void mafOpStack::Push(mafOp* op)   
//----------------------------------------------------------------------------
{
  op->m_Next = m_Stack;
  m_Stack = op;
}

//----------------------------------------------------------------------------
mafOp* mafOpStack::Pop()   
//----------------------------------------------------------------------------
{
  mafOp* op = m_Stack;
  m_Stack = op->m_Next;
  return op;
}

//----------------------------------------------------------------------------
void mafOpStack::Clear()   
//----------------------------------------------------------------------------
{
  while(m_Stack)
  {
	  delete Pop();
  }
}
